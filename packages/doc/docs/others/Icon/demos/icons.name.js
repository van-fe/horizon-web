export function getIconName() {
  if (icon_none_suffix_name.value.length) return;
  const xhr = new XMLHttpRequest();
  xhr.open('get', ICON_FONT_URL, true);
  xhr.responseType = 'blob';
  xhr.onload = function () {
    if (this.status === 200) {
      const reader = new FileReader();
      reader.onload = function () {
        if (!reader.result) return;
        const result_str = reader.result;
        const regex = /\.n-icon_(.+?)\:/g;
        let result;
        while ((result = regex.exec(result_str)) !== null) {
          const full_name = result[1];
          if (
            !icon_special_name.value.includes(full_name) &&
            !display_none_icon.includes(full_name)
          ) {
            if (full_name.includes('_filled')) {
              icon_filled_name.value.push(full_name);
            } else {
              icon_none_suffix_name.value.push(full_name);
            }
          }
        }
        icon_none_suffix_name.value.sort();
        icon_filled_name.value.sort();
      };
      reader.readAsText(this.response);
    }
  };
  xhr.send();
}
